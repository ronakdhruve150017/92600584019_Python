s = "Hello Python"

# Slicing
print(s[0:5])
print(s[1:5:1])
print(s[2:])
print(s[:5])
print(s[-1])
print(s[-3:])
print(s[:-2])
print(s[::-1])
print(s[::-2])


# Formatting
name = "Ronak"
age = 21
print("My name is {} and I am {} years old".format(name, age))


# Built-in functions
print(s.upper())
print(s.lower())
print(s.capitalize())
print(s.title())
print(s.strip())
print(s.find("o"))
print(s.count("o"))
print(s.split())
print(s.startswith("l"))
print(s.endswith("p"))
print(s.isalpha())
print(s.isdigit())
print(len(s))
print(s.replace("Python", "World"))

