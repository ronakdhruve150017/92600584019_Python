# Program to demonstrate conditional statements in Python

# 1. if statement
age = 20

if age >= 18:
    print("You are eligible to vote.")


# 2. if-else statement
number = 7

if number % 2 == 0:
    print("The number is even.")
else:
    print("The number is odd.")


# 3. if-elif-else statement
marks = 75

if marks >= 90:
    print("Grade: A+")
elif marks >= 75:
    print("Grade: A")
elif marks >= 60:
    print("Grade: B")
elif marks >= 40:
    print("Grade: C")
else:
    print("Grade: F")
